-- Funcion con parametros: Calcula el total vendido en el mes para la sucursal de un empleado
CREATE OR REPLACE FUNCTION F_CALCULAR_TOTAL_VENDIDO_EMPLEADO_POR_MES(
    P_ID_EMPLEADO IN NUMBER,
    P_MES         IN NUMBER,
    P_ANIO        IN NUMBER
) RETURN VARCHAR2 IS
    V_NOMBRE_COMPLETO VARCHAR2(150 CHAR);
    V_TOTAL_VENDIDO   NUMBER(15);
BEGIN
    -- Obtener nombre del empleado
    SELECT TRIM(
               E.PRIMER_NOMBRE || ' ' || 
               NVL2(E.SEGUNDO_NOMBRE, E.SEGUNDO_NOMBRE || ' ', '') || 
               E.PRIMER_APELLIDO || 
               NVL2(E.SEGUNDO_APELLIDO, ' ' || E.SEGUNDO_APELLIDO, '')
           )
    INTO   V_NOMBRE_COMPLETO
    FROM   EMPLEADO E
    WHERE  E.ID = P_ID_EMPLEADO;

    -- Sumar ventas del período
    SELECT NVL(SUM(V.TOTAL), 0)
    INTO   V_TOTAL_VENDIDO
    FROM   VENTA V 
    INNER JOIN SUCURSAL S ON S.ID = V.SUCURSAL_ID
    INNER JOIN EMPLEADO E ON S.ID = E.SUCURSAL_ID
    WHERE  EXTRACT(YEAR FROM V.FECHA_VENTA) = P_ANIO
      AND  EXTRACT(MONTH FROM V.FECHA_VENTA) = P_MES
      AND  E.ID = P_ID_EMPLEADO;

    RETURN V_NOMBRE_COMPLETO || ': $' || V_TOTAL_VENDIDO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Empleado ID ' || P_ID_EMPLEADO || ' no encontrado en el sistema.';
    WHEN OTHERS THEN
        RETURN 'Error al calcular ventas: ' || SQLERRM;
END F_CALCULAR_TOTAL_VENDIDO_EMPLEADO_POR_MES;
/

-- Funcion sin parametros: Retorna el monto acumulado global de ventas
CREATE OR REPLACE FUNCTION F_TOTAL_VENTAS_HISTORICO
RETURN NUMBER IS
    V_TOTAL_GLOBAL NUMBER(15);
BEGIN
    SELECT NVL(SUM(TOTAL), 0)
    INTO   V_TOTAL_GLOBAL
    FROM   VENTA;

    RETURN V_TOTAL_GLOBAL;
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END F_TOTAL_VENTAS_HISTORICO;
/

-- Pruebas de funcion con parametros
SELECT F_CALCULAR_TOTAL_VENDIDO_EMPLEADO_POR_MES(1, 7, 2026) AS RESULTADO FROM DUAL;
SELECT F_CALCULAR_TOTAL_VENDIDO_EMPLEADO_POR_MES(1, 1, 2026) AS RESULTADO FROM DUAL;
SELECT F_CALCULAR_TOTAL_VENDIDO_EMPLEADO_POR_MES(999, 7, 2026) AS RESULTADO FROM DUAL;

-- Pruebas de funcion sin parametros en sentencias SQL
SELECT F_TOTAL_VENTAS_HISTORICO() AS RECAUDACION_TOTAL_HISTORICA FROM DUAL;
SELECT F_TOTAL_VENTAS_HISTORICO() * 0.19 AS IVA_TOTAL_ESTIMADO FROM DUAL;
